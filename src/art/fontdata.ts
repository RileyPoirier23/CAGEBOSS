/** Normalise typographic characters to ones the fonts have. */
export function normalizeText(s: string): string {
  return s
    .replace(/[‘’‛]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/…/g, '...')
    .replace(/ /g, ' ')
    .replace(/[éèêë]/g, 'e')
    .replace(/[áàâä]/g, 'a')
    .replace(/[íìîï]/g, 'i')
    .replace(/[óòôö]/g, 'o')
    .replace(/[úùûü]/g, 'u')
    .replace(/ñ/g, 'n')
    .replace(/ç/g, 'c');
}

export function glyphFor(face: FontFace, ch: string): string[] | null {
  if (face.upperOnly) ch = ch.toUpperCase();
  return face.glyphs[ch] ?? null;
}

export function charWidth(face: FontFace, ch: string): number {
  if (ch === ' ') return face.spaceWidth;
  const g = glyphFor(face, ch) ?? glyphFor(face, '?');
  return g ? g[0].length : face.spaceWidth;
}

/** Width in pixels of a single line (no wrapping, markup stripped). */
export function measureLine(face: FontFace, s: string): number {
  let w = 0;
  let first = true;
  for (const ch of stripMarkup(normalizeText(s))) {
    if (!first) w += face.letterSpacing;
    w += charWidth(face, ch);
    first = false;
  }
  return w;
}

/** Colour markup: {#rrggbb}text{/}  — stripped for measuring. */
export function stripMarkup(s: string): string {
  return s.replace(/\{#[0-9a-fA-F]{6}\}|\{\/\}/g, '');
}

/**
 * Word-wrap text to a pixel width. Preserves explicit newlines and colour
 * markup tokens (which have zero width).
 */
export function wrapText(face: FontFace, text: string, maxWidth: number): string[] {
  const out: string[] = [];
  for (const para of normalizeText(text).split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const candidate = line.length ? line + ' ' + word : word;
      if (measureLine(face, candidate) <= maxWidth || line.length === 0) {
        if (line.length === 0 && measureLine(face, word) > maxWidth) {
          // hard-break very long word
          let chunk = '';
          for (const ch of word) {
            if (measureLine(face, chunk + ch) > maxWidth && chunk) {
              out.push(chunk);
              chunk = ch;
            } else chunk += ch;
          }
          line = chunk;
        } else line = candidate;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
